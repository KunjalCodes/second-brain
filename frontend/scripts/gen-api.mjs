// Regenerates lib/api/schema.d.ts from the backend's OpenAPI document
// (docs/PHASE10_PLAN.md section 18). The schema is produced from the FastAPI
// app object directly -- no running server, database or network needed.
// Run after any backend API change: `npm run gen:api`, then commit the result.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const backend = path.resolve(here, "../../backend");
const json = execFileSync(
  "uv",
  [
    "run",
    "python",
    "-c",
    "import json; from app.main import create_app; print(json.dumps(create_app().openapi(), sort_keys=True))",
  ],
  // Identity mode does not affect the schema; pin it so a developer's .env
  // cannot make generation fail on an unrelated setting.
  { cwd: backend, encoding: "utf8", env: { ...process.env, AUTH_MODE: "session", ALLOW_USER_ID_HEADER: "false" } },
);
const ast = await openapiTS(JSON.parse(json));
const header =
  "/* eslint-disable */\n// GENERATED by scripts/gen-api.mjs from the backend OpenAPI schema. DO NOT EDIT.\n\n";
writeFileSync(path.resolve(here, "../lib/api/schema.d.ts"), header + astToString(ast));
console.log("wrote lib/api/schema.d.ts");
